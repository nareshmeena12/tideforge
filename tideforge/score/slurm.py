"""Perlmutter jobs for the tfbench scorer: writes $TF_ROOT/jobs/score_<name>.sbatch (outside the repo; edit this generator,
not the file). One GPU per job (shared QOS); everything runs offline (fetch first on a login node).

    python -m tideforge.score.slurm check [--time 04:00:00]
        the first GPU job: (1) the profiler of the old fev path on fev-bench with ft3_main, modes ON and OFF; (2) the new
        scorer on fev-bench with ft3_main, --groups both (the reproduction: ON should give 43.78, OFF 42.09, within ~0.1);
        (3) seasonal naive and ft3_main on the tfbench fast and full tiers (timings, cache size).
    python -m tideforge.score.slurm score --model CKPT [--model-id ID] [--tier full] [--groups auto] [--locked] [--time 01:00:00]
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

EVAL_ROOT = "$TF_ROOT/eval_t0"          # the old scorer's evaluation root R1 used (fev-bench data + reference CSVs cached)


def header(name: str, time: str, account: str) -> str:
    if not re.fullmatch(r"\d+:\d\d:\d\d", time):
        raise ValueError(f"--time {time!r}: HH:MM:SS")
    return f"""#!/bin/bash
# GENERATED by tideforge/score/slurm.py: edit the generator, not this file.
#SBATCH -A {account}
#SBATCH -C gpu
#SBATCH -q shared
#SBATCH -N 1
#SBATCH --gpus=1
#SBATCH -c 32
#SBATCH -t {time}
#SBATCH -J {name}
#SBATCH -o %x-%j.out
set -u
source "$SCRATCH/tideforge/repo/scripts/perlmutter/env.sh" || exit 2
cd "$TF_REPO" || exit 2
echo "$(date) job $SLURM_JOB_ID on $(hostname)"; git log --oneline -1; nvidia-smi --query-gpu=name,memory.total --format=csv
mkdir -p "$TF_ROOT/logs"
run() {{ echo "$(date) >>> $*"; "$@" || {{ echo "$(date) FAILED: $*"; exit 1; }}; }}
"""


def check_body() -> str:
    S = "python -m tideforge.score.run"
    return f"""run python -m tideforge.score.profile_fev --root "{EVAL_ROOT}" --ckpt "$FT3_MAIN_CKPT" --modes on,off --out "$TF_ROOT/results/profile_fev"
run {S} score --model "$FT3_MAIN_CKPT" --model-id ft3_main --fev-bench --eval-root "{EVAL_ROOT}" --groups both --experiment tfbench-scorer --why "scorer check: reproduce 43.78 / 42.09"
run {S} score --model seasonal_naive --tier fast
run {S} score --model "$FT3_MAIN_CKPT" --model-id ft3_main --tier fast --groups both
run {S} score --model seasonal_naive --tier full
run {S} score --model "$FT3_MAIN_CKPT" --model-id ft3_main --tier full --groups both
echo "=== profile"; cat "$TF_ROOT/results/profile_fev/profile.md"
for m in on off; do echo "=== fev-bench groups $m"; cat "$TF_ROOT/results/tfbench/ft3_main/fev-bench/fev-bench_fev-bench/groups_$m/stats.json"; done
for t in fast full; do for m in on off; do echo "=== tfbench $t groups $m"; cat "$TF_ROOT/results/tfbench/ft3_main/v1.1.0/${{t}}_tuning/groups_$m/stats.json"; done; done
echo "$(date) score_check JOB DONE"
"""


def score_body(a) -> str:
    extra = f" --model-id {a.model_id}" if a.model_id else ""
    extra += " --locked" if a.locked else ""
    return f"""run python -m tideforge.score.run score --model "{a.model}"{extra} --tier {a.tier} --groups {a.groups} --version {a.version}
echo "$(date) score JOB DONE"
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("--time", default="04:00:00")
    s = sub.add_parser("score")
    s.add_argument("--model", required=True)
    s.add_argument("--model-id")
    s.add_argument("--tier", default="full")
    s.add_argument("--groups", default="auto")
    s.add_argument("--version", default="v1.1.0")
    s.add_argument("--locked", action="store_true")
    s.add_argument("--time", default="01:00:00")
    for p in (c, s):
        p.add_argument("--out")
    a = ap.parse_args(argv)
    root, account = os.environ.get("TF_ROOT"), os.environ.get("NERSC_ACCOUNT")
    if not account:
        raise SystemExit("NERSC_ACCOUNT is not set (source scripts/perlmutter/env.sh)")
    name = "score_check" if a.cmd == "check" else f"score_{a.model_id or Path(a.model).stem}_{a.tier}" + ("_locked" if a.locked else "")
    if not a.out and not root:
        raise SystemExit("TF_ROOT is not set and no --out given")
    p = Path(a.out) if a.out else Path(root) / "jobs" / f"{name}.sbatch"
    p.parent.mkdir(parents=True, exist_ok=True)
    body = check_body() if a.cmd == "check" else score_body(a)
    p.write_bytes((header(name, a.time, account) + body).encode("utf-8"))
    print(f"wrote {p}\nsubmit: cd $TF_ROOT/logs && sbatch {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
