"""The adapter jobs: write $TF_ROOT/jobs/ad_<stage>.sbatch (outside the repo). One regular node, one background process per GPU
(CUDA_VISIBLE_DEVICES), no srun steps. Everything a job writes is under $TF_ROOT. Edit this generator, not the files.

    python -m tideforge.train.adjob write pilot   --time 03:00:00                  # AD.2 on R1.2 at 3e-4, 1e-3, 1B points, then P1 + P11
    python -m tideforge.train.adjob choose --probes $TF_ROOT/probes_ad --tags lr3e-4 lr1e-3
    python -m tideforge.train.adjob write ad12    --time 06:00:00 --lr <chosen>     # AD.1, AD.2, seeds 0, 1, then fev
    python -m tideforge.train.adjob write ad34    --time 12:00:00 --lr <chosen>     # AD.3, AD.4 (R1.4), only if AD.2 beat AD.1

choose: the pilot's rule (never fev or TIME): the lower of (mean P1 sql_on_vs_hidden over the non-decoy cells + P11's harm_summary).
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

import pandas as pd

from tideforge.probes.p11_overtrust import harm_summary

EVAL_ROOT = "$TF_ROOT/eval_t0"
PILOT_LRS = ("3e-4", "1e-3")
PY = "CUDA_VISIBLE_DEVICES={gpu} OMP_NUM_THREADS=32 python"
BACKBONE = {"AD.1": "R1.2", "AD.2": "R1.2", "AD.3": "R1.4", "AD.4": "R1.4"}


def tag(exp: str, seed: int) -> str:
    return f"{exp.replace('.', '').lower()}s{seed}"


def backbone(exp: str) -> str:
    return f'$(ls -t "$TF_ROOT"/runs/{BACKBONE[exp]}-*/final.pt | head -1)'


def latest(exp: str, seed: int) -> str:
    return f'$(ls -t "$TF_ROOT"/runs/{exp}-*-s{seed}-*/final.pt | head -1)'


def train_line(exp: str, seed: int, gpu: int, lr: str, points: str = "") -> str:
    extra = f" --points {points} --no-finish" if points else ""
    log = f"ad_{exp}_s{seed}" + (f"_lr{lr}" if points else "")
    return (f'{PY.format(gpu=gpu)} -m tideforge.train.adapter_train --exp {exp} --seed {seed} --backbone-ckpt "{backbone(exp)}" '
            f'--out "$TF_ROOT/runs" --lr {lr}{extra} > "$TF_ROOT/logs/{log}.log" 2>&1 &')


def stage_body(stage: str, lr: str | None) -> tuple[list[str], list[str]]:
    """(training lines, lines after training)."""
    if stage == "pilot":
        train = [train_line("AD.2", 0, i, x, "1e9") for i, x in enumerate(PILOT_LRS)]
        after = []
        for i, x in enumerate(PILOT_LRS):
            ck = f'$(sed -n "s/^run \\([^: ]*\\).*/\\1/p" "$TF_ROOT/logs/ad_AD.2_s0_lr{x}.log" | tail -1)'
            after.append(f'{PY.format(gpu=i)} -m tideforge.probes run --root "$TF_DATA/probes" --out "$TF_ROOT/probes_ad/lr{x}" '
                         f'--model m5 --ckpt "$TF_ROOT/runs/{ck}/final.pt" --probes P1,P11 '
                         f'> "$TF_ROOT/logs/ad_pilot_probes_{x}.log" 2>&1 &')
        after.append(f'{PY.format(gpu=2)} -m tideforge.probes run --root "$TF_DATA/probes" --out "$TF_ROOT/probes_ad/r12" '
                     f'--model m5 --ckpt "{backbone("AD.2")}" --probes P1,P11 > "$TF_ROOT/logs/ad_pilot_probes_r12.log" 2>&1 &')
        return train, after
    exps = ("AD.1", "AD.2") if stage == "ad12" else ("AD.3", "AD.4")
    cells = [(e, s) for e in exps for s in (0, 1)]
    train = [train_line(e, s, i, lr) for i, (e, s) in enumerate(cells)]
    after = [f'{PY.format(gpu=i)} -m tideforge.eval.score score --root "{EVAL_ROOT}" --ckpt "{tag(e, s)}={latest(e, s)}" --modes on '
             f'--skip-time > "$TF_ROOT/logs/ad_fev_{e}_s{s}.log" 2>&1 &' for i, (e, s) in enumerate(cells)]
    return train, after


def looks_lines(stage: str) -> list[str]:
    if stage == "pilot":
        return []
    exps = ("AD.1", "AD.2") if stage == "ad12" else ("AD.3", "AD.4")
    base = {"ad12": "r12", "ad34": "r14"}[stage]
    out = []
    for e in exps:
        for s in (0, 1):
            t = tag(e, s)
            out.append(f'python -m tideforge.eval.score check-identical --root "{EVAL_ROOT}" --a {t}baseon_s0 --b {base}baseon_s0 '
                       f'|| {{ echo "{t}: non-covariate tasks differ from the backbone"; exit 1; }}')
            out.append(f'echo "| $(date +%F) | {e} | {t}baseon_s0 (groups ON) | fev-bench (42 covariate tasks) | adapter, one counted look '
                       f'| scored; column from eval.where |" >> "$TF_ROOT/looks_pending.md"')
    return out


def render(stage: str, time: str, lr: str | None, account: str) -> str:
    if not re.fullmatch(r"\d+:\d\d:\d\d", time):
        raise ValueError(f"--time {time!r}: HH:MM:SS")
    if stage != "pilot" and not lr:
        raise ValueError("ad12 / ad34 need --lr (the pilot's choice)")
    train, after = stage_body(stage, lr)
    nl = "\n"
    start = lambda ls: nl.join(f"{x}\nPIDS+=($!)" for x in ls)      # noqa: E731
    return f"""#!/bin/bash
# GENERATED by tideforge/train/adjob.py: edit the generator, not this file.
#SBATCH -A {account}
#SBATCH -C gpu
#SBATCH -q regular
#SBATCH -N 1
#SBATCH --gpus=4
#SBATCH -c 128
#SBATCH -t {time}
#SBATCH -J ad_{stage}
#SBATCH -o %x-%j.out
#SBATCH --signal=B:USR1@120
#SBATCH --requeue
#SBATCH --open-mode=append
set -u
source "$SCRATCH/tideforge/repo/scripts/perlmutter/env.sh" || exit 2
export CUBLAS_WORKSPACE_CONFIG=":4096:8"
cd "$TF_REPO" || exit 2
mkdir -p "$TF_ROOT/runs" "$TF_ROOT/logs" "$TF_ROOT/probes_ad" "{EVAL_ROOT}"
echo "$(date) job $SLURM_JOB_ID on $(hostname)"; git log --oneline -1
PIDS=()
forward() {{
    echo "$(date) SIGUSR1: asking the runs to save and stop"
    for p in "${{PIDS[@]}}"; do kill -USR1 "$p" 2>/dev/null; done
    wait
    scontrol requeue "$SLURM_JOB_ID"; exit 0
}}
trap forward USR1
wait_all() {{
    RC=0
    for p in "${{PIDS[@]}}"; do
        while :; do wait "$p"; c=$?; kill -0 "$p" 2>/dev/null || break; done
        [ "$c" -eq 0 ] || RC=$c
    done
}}
{start(train)}
wait_all
if [ "$RC" -eq 3 ]; then scontrol requeue "$SLURM_JOB_ID"; exit 0; fi
[ "$RC" -eq 0 ] || {{ echo "$(date) a run FAILED (exit $RC): see $TF_ROOT/logs/ad_*.log"; exit 1; }}
PIDS=()
{start(after)}
wait_all
[ "$RC" -eq 0 ] || {{ echo "$(date) a score FAILED (exit $RC)"; exit 1; }}
{nl.join(looks_lines(stage))}
echo "$(date) ad_{stage} JOB DONE"
"""


def pilot_score(results: Path) -> float:
    df = pd.read_csv(results).groupby(["probe", "cell", "mode", "metric"], sort=False).tail(1)
    p1 = df[(df.probe == "P1") & (df.metric == "sql_on_vs_hidden") & ~df.cell.str.startswith("decoy")]
    p11 = df[(df.probe == "P11") & (df.metric == "harm")]
    if p1.empty or p11.empty:
        raise SystemExit(f"{results}: P1 or P11 rows missing")
    return float(p1["value"].mean()) + harm_summary(dict(zip(p11.cell, p11["value"])))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=("write", "choose"))
    ap.add_argument("stage", nargs="?", choices=("pilot", "ad12", "ad34"))
    ap.add_argument("--time")
    ap.add_argument("--lr")
    ap.add_argument("--probes")
    ap.add_argument("--tags", nargs="+")
    a = ap.parse_args(argv)
    if a.cmd == "choose":
        s = {t: pilot_score(Path(a.probes) / t / "results.csv") for t in a.tags}
        for t, v in s.items():
            print(f"{t}: {v:.4f}")
        print(f"chosen: {min(s, key=s.get)}")
        return 0
    root, account = os.environ.get("TF_ROOT"), os.environ.get("NERSC_ACCOUNT")
    if not root or not account:
        raise SystemExit("TF_ROOT and NERSC_ACCOUNT must be set (source scripts/perlmutter/env.sh)")
    p = Path(root) / "jobs" / f"ad_{a.stage}.sbatch"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(render(a.stage, a.time, a.lr, account).encode("utf-8"))
    print(f"wrote {p}\nsubmit: cd $TF_ROOT/logs && sbatch {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
