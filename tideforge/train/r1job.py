"""R1's node job: writes $TF_ROOT/jobs/r1.sbatch (outside the repo). One regular node, four GPUs (GPUS: 30M alone, 5M two in a row),
then fev (groups ON, no TIME) on the four final.pt. Edit this generator, not the file.

    python -m tideforge.train.r1job --time 30:00:00 [--micro-rows 512] [--out $TF_ROOT/jobs/r1.sbatch]

--time: max(30M projected, 2 x 5M projected) + 30%, from tools/m30_check.py. --micro-rows goes to the m30 runs only (0 = none). The job writes
under $TF_ROOT only: runs, logs, results, eval_t0, looks_pending.md.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

from tideforge.train import recipe as RC

RUNS = ("R1.1", "R1.2", "R1.3", "R1.4", "R1.5", "R1.6")
GPUS = (("R1.3",), ("R1.4",), ("R1.1", "R1.5"), ("R1.2", "R1.6"))    # one chain per GPU, one run after the other
NGPU = len(GPUS)
EVAL_ROOT = "$TF_ROOT/eval_t0"


def step(gpu) -> str:
    """Background processes in the batch script, not parallel srun steps: in job 60660013 only one of four steps ran."""
    return f"CUDA_VISIBLE_DEVICES={gpu} OMP_NUM_THREADS=32 python"


def tag(exp: str) -> str:
    return exp.replace(".", "").lower()


def render(time: str, micro: int, account: str) -> str:
    if not re.fullmatch(r"\d+:\d\d:\d\d", time):
        raise ValueError(f"--time {time!r}: HH:MM:SS")
    item = lambda e: f"{e}:{micro if RC.load(e).sections['model']['d_model'] == 512 else 0}"    # noqa: E731
    train = [f'chain {i} "' + " ".join(item(e) for e in g) + '"' for i, g in enumerate(GPUS)]
    score = []
    for i in range(NGPU):                                               # one queue per GPU
        body = "".join(f'    ck=$(ls -t "$TF_ROOT"/runs/{e}-*/final.pt | head -1)\n'
                       f'    [ -n "$ck" ] || {{ echo "no final.pt for {e}"; exit 1; }}\n'
                       f'    {step(i)} -m tideforge.eval.score score --root "{EVAL_ROOT}" --ckpt "{tag(e)}=$ck" --modes on --skip-time '
                       f'> "$TF_ROOT/logs/r1_fev_{e}.log" 2>&1 || exit 1\n' for e in RUNS[i::NGPU])
        score.append(f"(\n{body}) &\nPIDS+=($!)")
    looks = "\n".join(f'echo "| $(date +%F) | {e} | {tag(e)}baseon_s0 (groups ON) | fev-bench | R1, one counted look | scored; '
                      f'skill from the board |" >> "$TF_ROOT/looks_pending.md"' for e in RUNS)
    nl = "\n"
    return f"""#!/bin/bash
# GENERATED by tideforge/train/r1job.py: edit the generator, not this file.
#SBATCH -A {account}
#SBATCH -C gpu
#SBATCH -q regular
#SBATCH -N 1
#SBATCH --gpus=4
#SBATCH -c 128
#SBATCH -t {time}
#SBATCH -J r1
#SBATCH -o %x-%j.out
#SBATCH --signal=B:USR1@120
#SBATCH --requeue
#SBATCH --open-mode=append
set -u
source "$SCRATCH/tideforge/repo/scripts/perlmutter/env.sh" || exit 2
export CUBLAS_WORKSPACE_CONFIG=":4096:8"
cd "$TF_REPO" || exit 2
echo "$(date) job $SLURM_JOB_ID on $(hostname), restart count ${{SLURM_RESTART_COUNT:-0}}"
mkdir -p "$TF_ROOT/runs" "$TF_ROOT/logs" "{EVAL_ROOT}"
git log --oneline -1
PIDS=()
forward() {{
    echo "$(date) SIGUSR1: asking the runs to save and stop"
    for p in "${{PIDS[@]}}"; do kill -USR1 "$p" 2>/dev/null; done
    wait
    scontrol requeue "$SLURM_JOB_ID"; exit 0
}}
trap forward USR1
# one GPU's runs in order; a subshell ignores the parent's trap, so it forwards USR1 to its own process and keeps waiting for it
chain() {{
    (
    trap 'kill -USR1 "$p" 2>/dev/null' USR1
    for item in $2; do
        e=${{item%:*}}; m=${{item#*:}}
        extra=""; [ "$m" -eq 0 ] || extra="--micro-rows $m"
        {step("$1")} -m tideforge.train.trainer --exp "$e" --seed 0 --out "$TF_ROOT/runs" $extra > "$TF_ROOT/logs/r1_$e.log" 2>&1 &
        p=$!
        wait "$p"; c=$?
        while kill -0 "$p" 2>/dev/null; do wait "$p"; c=$?; done
        [ "$c" -eq 0 ] || exit "$c"
    done
    ) &
    PIDS+=($!)
}}
wait_all() {{
    RC=0
    for p in "${{PIDS[@]}}"; do wait "$p"; c=$?; [ "$c" -eq 0 ] || RC=$c; done
}}
{nl.join(train)}
wait_all
if [ "$RC" -eq 3 ]; then echo "$(date) a trainer stopped to be requeued"; scontrol requeue "$SLURM_JOB_ID"; exit 0; fi
[ "$RC" -eq 0 ] || {{ echo "$(date) a run FAILED (exit $RC): see $TF_ROOT/logs/r1_*.log"; exit 1; }}
echo "$(date) training done; fev"
PIDS=()
{nl.join(score)}
wait_all
[ "$RC" -eq 0 ] || {{ echo "$(date) a score FAILED (exit $RC): see $TF_ROOT/logs/r1_fev_*.log"; exit 1; }}
{looks}
echo "$(date) r1 JOB DONE"
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--time", required=True)
    ap.add_argument("--micro-rows", type=int, default=0)
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    root, account = os.environ.get("TF_ROOT"), os.environ.get("NERSC_ACCOUNT")
    if not account:
        raise SystemExit("NERSC_ACCOUNT is not set (source scripts/perlmutter/env.sh)")
    if not a.out and not root:
        raise SystemExit("TF_ROOT is not set and no --out given")
    p = Path(a.out) if a.out else Path(root) / "jobs" / "r1.sbatch"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(render(a.time, a.micro_rows, account).encode("utf-8"))
    print(f"wrote {p}\nsubmit: cd $TF_ROOT/logs && sbatch {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
