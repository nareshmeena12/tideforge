"""Writes tideforge's Perlmutter batch scripts (the generator pattern of tidemark/pretrain/slurm.py: edit this file, not the
.sbatch files; the scripts are committed).

    python -m tideforge.slurm            # (re)write scripts/perlmutter/*.sbatch
    python -m tideforge.slurm --check    # exit 1 if a committed script differs from what this would write

Jobs:
  e03_score.sbatch   E0.3 scoring in the background: nofill_delete and nofill_mask (groups ON and OFF) and cov_mask (groups ON
                     only), one GPU per variant (shared QOS, 3 GPUs), then the E0.3 table against tidemark's board as the
                     baseline. score_groups resumes
                     per (tag, task), so a job that hits its time limit is requeued and continues where it stopped.
Submit from the log folder (the job's output lands there as <job name>-<job id>.out):
    cd $TF_ROOT/logs && sbatch $SCRATCH/tideforge/repo/scripts/perlmutter/e03_score.sbatch
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ACCOUNT = "m4392_g"
OUT = Path(__file__).resolve().parents[1] / "scripts" / "perlmutter"

HEADER = """#!/bin/bash
# GENERATED by tideforge/slurm.py: edit the generator, not this file.
#SBATCH -A {account}
#SBATCH -C gpu
#SBATCH -q {qos}
#SBATCH -N 1
#SBATCH --gpus={gpus}
#SBATCH -c {cpus}
#SBATCH -t {time}
#SBATCH -J {name}
#SBATCH -o %x-%j.out
#SBATCH --signal=B:USR1@120
#SBATCH --requeue
#SBATCH --open-mode=append
# {what}
set -u
source "$SCRATCH/tideforge/repo/scripts/perlmutter/env.sh" || exit 2
echo "$(date) job $SLURM_JOB_ID on $(hostname), restart count ${{SLURM_RESTART_COUNT:-0}}"
# two minutes before the time limit: requeue (the scorer resumes per task, so nothing is lost but the task in progress)
trap 'echo "$(date) SIGUSR1: time limit close, requeueing"; scontrol requeue "$SLURM_JOB_ID"; exit 0' USR1
"""

JOBS = {
    "e03_score": dict(
        qos="shared", gpus=3, cpus=96, time="06:00:00",
        what="E0.3: ft3_main under nofill_delete, nofill_mask (ON + OFF) and cov_mask (ON), then the table vs tidemark's board.",
        body="""bash "$TF_REPO/scripts/perlmutter/e03_nan.sh" score &
wait $! || { echo "$(date) E0.3 scoring FAILED"; exit 1; }
bash "$TF_REPO/scripts/perlmutter/e03_nan.sh" table
echo "$(date) E0.3 JOB DONE"
"""),
}


def render(name: str) -> str:
    j = JOBS[name]
    return HEADER.format(account=ACCOUNT, name=name, **{k: v for k, v in j.items() if k != "body"}) + j["body"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = []
    for name in JOBS:
        p, text = OUT / f"{name}.sbatch", render(name)
        if a.check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                bad.append(p.name)
        else:
            p.write_bytes(text.encode("utf-8"))
            print(f"wrote {p}")
    if bad:
        print("differ from tideforge/slurm.py:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
