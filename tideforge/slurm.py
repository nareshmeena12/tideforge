"""Writes tideforge's Perlmutter batch scripts (the generator pattern of tidemark/pretrain/slurm.py: edit this file, not the
.sbatch files; the scripts are committed).

    python -m tideforge.slurm            # (re)write scripts/perlmutter/*.sbatch
    python -m tideforge.slurm --check    # exit 1 if a committed script differs from what this would write

Jobs:
  e03_score.sbatch   E0.3 + E0.10 scoring in the background: nofill_delete and nofill_mask (groups ON and OFF), cov_mask (groups
                     ON only) and E0.10's target_enc / order_corr / both (groups ON, fev covariate tasks only), eight
                     (variant, mode) units queued over the 4 GPUs of a full regular node (a unit starts when a GPU frees
                     up), then the E0.3 table and the E0.10 comparisons against tidemark's board as the baseline. score_groups resumes per (tag, task), so a job that hits its time limit is requeued and continues where it stopped.
QOS limits (Perlmutter GPU nodes: 4 GPUs, 128 cores): shared at most half a node (2 GPUs, 64 cores), regular a full node.
check() refuses a job above them; main() prints each job's estimated GPU-hours (estimates, from UNITS_H) and the
allocated maximum (GPUs x time limit).
  t3_e07.sbatch      E0.7 + E0.8: one regular node, one 5M run per GPU (TRAIN_JOBS: 3 B0 seeds + E0.8 seed 0, owner
                     2026-10-29: no idle slot). SIGUSR1 two minutes before the limit is forwarded to the four trainers (each
                     saves last.pt and exits 3), then the job requeues itself; finished runs stop at once on restart.
                     GPU-h estimate: 100B points / TRAIN_PTS_PER_S per run (E0.9's measured deterministic-mode rate once it
                     exists; before that ESTIMATE_PTS_PER_S, an estimate), printed by main() before anything is submitted.
Submit from the log folder (the job's output lands there as <job name>-<job id>.out):
    cd $TF_ROOT/logs && sbatch $SCRATCH/tideforge/repo/scripts/perlmutter/e03_score.sbatch
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ACCOUNT = "m4392_g"
OUT = Path(__file__).resolve().parents[1] / "scripts" / "perlmutter"

HEADER = """#!/bin/bash
# GENERATED by tideforge/slurm.py: edit the generator, not this file.
#SBATCH -A {account}
#SBATCH -C gpu
#SBATCH -q {qos}
#SBATCH -N 1
#SBATCH --gpus={gpus}
#SBATCH -c {cpus}
#SBATCH -t {time}
#SBATCH -J {name}
#SBATCH -o %x-%j.out
#SBATCH --signal=B:USR1@120
#SBATCH --requeue
#SBATCH --open-mode=append
# {what}
set -u
source "$SCRATCH/tideforge/repo/scripts/perlmutter/env.sh" || exit 2
echo "$(date) job $SLURM_JOB_ID on $(hostname), restart count ${{SLURM_RESTART_COUNT:-0}}"
# two minutes before the time limit: requeue (the scorer resumes per task, so nothing is lost but the task in progress)
trap 'echo "$(date) SIGUSR1: time limit close, requeueing"; scontrol requeue "$SLURM_JOB_ID"; exit 0' USR1
"""

NODE_GPUS, NODE_CPUS = 4, 128
QOS = {"shared": dict(gpus=2, cpus=64, hours=48), "regular": dict(gpus=4, cpus=128, hours=48)}

# E0.3 units (variant:mode, the order e03_nan.sh queues them) and their estimated hours on one A100 (estimates, not measured)
UNITS_H = {"e03_score": {"nofill_delete:on": 2.5, "nofill_mask:on": 2.5, "nofill_delete:off": 2.0, "nofill_mask:off": 2.0,
                         "cov_mask:on": 1.5, "target_enc:on": 1.0, "order_corr:on": 1.0, "both:on": 1.0}}

JOBS = {
    "e03_score": dict(
        qos="regular", gpus=4, cpus=128, time="06:00:00",
        what="E0.3: ft3_main under nofill_delete, nofill_mask (ON, OFF) and cov_mask (ON); E0.10: target_enc, order_corr, both "
             "(ON, fev covariate tasks); then the tables vs tidemark's board.",
        body="""bash "$TF_REPO/scripts/perlmutter/e03_nan.sh" score &
wait $! || { echo "$(date) E0.3 scoring FAILED"; exit 1; }
bash "$TF_REPO/scripts/perlmutter/e03_nan.sh" table
echo "$(date) E0.3 JOB DONE"
"""),
}


# ---- 5M training node jobs: (experiment, seed) per GPU slot
TRAIN_PTS_PER_S = None              # E0.9's deterministic-mode points/s per GPU (tideforge.train.throughput report): fill in
ESTIMATE_PTS_PER_S = 3.0e7          # ESTIMATE until E0.9 runs (model ~1.1 MFLOP / point at 15-30% of A100 bf16 + generation)
TRAIN_POINTS = 100e9
TRAIN_JOBS = {
    "t3_e07": dict(qos="regular", gpus=4, cpus=128, time="12:00:00", runs=[("E0.7", 0), ("E0.7", 1), ("E0.7", 2), ("E0.8", 0)],
                   what="E0.7 (5M B0, seeds 0-2) and E0.8 (white-noise control, seed 0): one run per GPU, then finish each"),
}

TRAIN_BODY = """mkdir -p "$TF_ROOT/runs" "$TF_ROOT/logs"
git -C "$TF_REPO" log --oneline -1
PIDS=()
forward() {{
    echo "$(date) SIGUSR1: asking the trainers to save and stop"
    for p in "${{PIDS[@]}}"; do kill -USR1 "$p" 2>/dev/null; done
    wait
    scontrol requeue "$SLURM_JOB_ID"; exit 0
}}
trap forward USR1
{launch}
RC=0
for p in "${{PIDS[@]}}"; do wait "$p"; c=$?; [ "$c" -eq 0 ] || RC=$c; done
if [ "$RC" -eq 3 ]; then echo "$(date) a trainer stopped to be requeued"; scontrol requeue "$SLURM_JOB_ID"; exit 0; fi
[ "$RC" -eq 0 ] || {{ echo "$(date) a run FAILED (exit $RC): see $TF_ROOT/logs/{name}_*.log"; exit 1; }}
echo "$(date) {name} JOB DONE"
"""
LAUNCH = ('CUDA_VISIBLE_DEVICES={gpu} python -m tideforge.train.trainer --exp {exp} --seed {seed} --out "$TF_ROOT/runs" '
          '> "$TF_ROOT/logs/{name}_{exp}_s{seed}.log" 2>&1 &')


def train_estimate(name: str) -> str:
    j = TRAIN_JOBS[name]
    rate, kind = (TRAIN_PTS_PER_S, "measured (E0.9)") if TRAIN_PTS_PER_S else (ESTIMATE_PTS_PER_S, "ESTIMATE (E0.9 not in yet)")
    h = TRAIN_POINTS / rate / 3600
    if h * 1.15 > hours(j["time"]):
        raise ValueError(f"{name}: a run needs about {h:.1f} h (+15% for validation / checkpoints), above the {j['time']} limit; "
                         "the job would requeue (allowed, but raise the limit)")
    n = len(j["runs"])
    return (f"{name}: {n} runs x {h:.1f} h = {n * h:.1f} GPU-h busy (rate {rate:.2e} pts/s per GPU, {kind}); node "
            f"wall time about {h:.1f} h; allocated at most {j['gpus'] * hours(j['time']):.1f} GPU-h "
            f"({j['gpus']} x {j['time']}, QOS {j['qos']})")


def render_train(name: str) -> str:
    j = TRAIN_JOBS[name]
    check(j)
    if len(j["runs"]) > j["gpus"]:
        raise ValueError(f"{name}: {len(j['runs'])} runs for {j['gpus']} GPUs (one run per GPU at 5M)")
    launch = "".join(LAUNCH.format(gpu=i, exp=e, seed=sd, name=name) + "\nPIDS+=($!)\n" for i, (e, sd) in enumerate(j["runs"]))
    head = HEADER.format(account=ACCOUNT, name=name, **{k: v for k, v in j.items() if k not in ("body", "runs")})
    head = head.split("# two minutes before the time limit")[0]          # the scorer's trap: replaced by forward() below
    head += "# two minutes before the time limit: SIGUSR1 is forwarded to the trainers (save + exit 3), then requeue\n"
    return head + TRAIN_BODY.format(launch=launch.rstrip("\n"), name=name)


def hours(time: str) -> float:
    h, m, s = (int(x) for x in time.split(":"))
    return h + m / 60 + s / 3600


def check(job: dict) -> None:
    """Raise ValueError if the job asks for more than its QOS allows (or more than a node has)."""
    q = QOS.get(job["qos"])
    if q is None:
        raise ValueError(f"unknown QOS {job['qos']!r} (known: {sorted(QOS)})")
    for k in ("gpus", "cpus"):
        if not 1 <= job[k] <= q[k]:
            raise ValueError(f"{k}={job[k]} outside 1..{q[k]} allowed by QOS {job['qos']}")
    if hours(job["time"]) > q["hours"]:
        raise ValueError(f"time {job['time']} above the {q['hours']} h limit of QOS {job['qos']}")
    if job["cpus"] > job["gpus"] * NODE_CPUS // NODE_GPUS:
        raise ValueError(f"cpus={job['cpus']} above {NODE_CPUS // NODE_GPUS} per GPU x {job['gpus']} GPUs")


def makespan(units_h: list[float], gpus: int) -> float:
    """Hours until the last unit ends when units start in list order on the first free GPU (what e03_nan.sh does)."""
    free = [0.0] * gpus
    for h in units_h:
        i = free.index(min(free))
        free[i] += h
    return max(free)


def estimate(name: str) -> str:
    j, u = JOBS[name], list(UNITS_H.get(name, {}).values())
    busy, span = sum(u), makespan(u, j["gpus"])
    if span > hours(j["time"]):
        raise ValueError(f"{name}: estimated makespan {span:.1f} h above its time limit {j['time']}")
    return (f"{name}: estimated {busy:.1f} GPU-h busy, makespan {span:.1f} h on {j['gpus']} GPUs (estimates); "
            f"allocated at most {j['gpus'] * hours(j['time']):.1f} GPU-h ({j['gpus']} x {j['time']}, QOS {j['qos']})")


def render(name: str) -> str:
    j = JOBS[name]
    check(j)
    return HEADER.format(account=ACCOUNT, name=name, **{k: v for k, v in j.items() if k != "body"}) + j["body"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = []
    jobs = [(n, estimate, render) for n in JOBS] + [(n, train_estimate, render_train) for n in TRAIN_JOBS]
    for name, est, rend in jobs:
        print(est(name))
        p, text = OUT / f"{name}.sbatch", rend(name)
        if a.check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                bad.append(p.name)
        else:
            p.write_bytes(text.encode("utf-8"))
            print(f"wrote {p}")
    if bad:
        print("differ from tideforge/slurm.py:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
