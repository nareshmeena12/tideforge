def build() -> str:
    core = (TP / "ft3_core.py").read_text(encoding="utf-8").splitlines()
    parts = [HEADER]
    for a, b in CORE_RANGES:
        parts.append(f"# >>> ft3_core.py L{a}-L{b}\n" + "\n".join(core[a - 1:b]) + "\n# <<< ft3_core.py\n\n")
    m = (TP / "model.py").read_text(encoding="utf-8")
    i = m.index("class MaskedLossDecoder")
    parts.append("# >>> tidemark/real/model.py class MaskedLossDecoder .. end\n" + m[i:].rstrip() + "\n# <<< model.py\n")
    return "".join(parts)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("ft3_model.py matches the source" if ok else "ft3_model.py differs from tools/port_model.py's output")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
